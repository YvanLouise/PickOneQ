export function createScenes(legacy) {
  return legacy.map(q => {
    const [title, background, sceneType, labels] = scenes[q.id.slice(5)];
    // Keep historical wording intact; only the new edition uses the revised explanation.
    const answer = q.id === 'seed-cost' ? '没有付款不等于没有代价：你放弃了把这段时间用于最佳替代活动的机会。' : q.id === 'seed-bias' ? '记录只保留支持原判断的信息，不能公平检验这个判断。' : q.id === 'seed-dns' ? '它需要先把可读名称对应到网络地址；找到地址还不等于收到网页。' : q.id === 'seed-cache' ? '不一定：满足复用条件时，浏览器可以使用之前保存的响应。' : q.answer;
    const explanation = explanations[q.id.slice(5)];
    return { ...q, id: q.id.replace('seed-', 'scene-'), previousId: q.id, title, background, answer: explanation?.[0] || answer, reasoning: explanation?.[1] || q.reasoning,
      sceneType, judgmentType: sceneType === 'tradeoff' ? 'conditional' : 'determinate',
      choices: labels?.map((label, i) => ({ id: String(i + 1), label })),
      sceneSummary: `${q.concepts.join('、')}：${background}`, conceptReveal: `这个情境可以用“${q.concepts.join('、')}”来理解。${q.misconception}`,
      contentDesignVersion: 2, version: 2, model: 'editorial-v2', relatedId: undefined, relatedPrompt: '换个情境试试',
    };
  });
}
